def test_the_contrast_ratio_is_wcag_2():
    black, white = parse_color("#000000", "x"), parse_color("#ffffff", "x")
    assert round(contrast(black, white), 1) == 21.0 and contrast(white, white) == 1.0
    # a known pair: #767676 on white is the classic 4.54:1 (just over AA)
    assert round(contrast(parse_color("#767676", "x"), white), 2) == 4.54
    assert minimum_ratio(12) == 4.5 and minimum_ratio(24) == 3.0 and minimum_ratio("icon") == 3.0


def test_every_shipped_theme_reads_at_4_5_to_1():
    for path in sorted(THEMES_DIR.glob("*.toml")):
        assert unreadable(read_theme(path).colors) == [], path.name
    # the pairs cover the UI's text on its grounds, the title bar, the tooltips, the map, the tiles
    texts = {t for texts, _, _ in READABLE for t in texts}
    assert {
        "text",
        "dim",
        "muted",
        "gold",
        "headerText",
        "tipText",
        "mapText",
        "diffYellow",
        "chatEmote",
    } <= texts
    grounds = {g for _, grounds, _ in READABLE for g in grounds}
    assert {"bg", "panel", "header", "mapTextRim", "tileGold"} <= grounds


def test_an_unreadable_theme_does_not_compile(tmp_path):
    for f in THEMES_DIR.glob("*.toml"):
        shutil.copy(f, tmp_path / f.name)
    path = tmp_path / "teal.toml"
    text = path.read_text(encoding="utf-8")
    assert 'dim = "#999999"' in text
    path.write_text(text.replace('dim = "#999999"', 'dim = "#444444"'), encoding="utf-8")
    with pytest.raises(
        ThemeError, match=r"teal: unreadable \(WCAG contrast\): dim on bg 1\.\d\d < 4\.5"
    ):
        read_themes(tmp_path)
    # the failing pair is named with its ratio, every one of them
    theme = read_theme(path)
    assert [p.split(" ")[0:3] for p in unreadable(theme.colors)] == [
        ["dim", "on", "bg"],
        ["dim", "on", "panel"],
    ]
