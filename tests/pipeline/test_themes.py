def test_the_committed_themes_lua_is_current():
    assert build_themes(check=True), "run: python -m bastians_build themes"


def test_the_themes_teal_first_each_complete():
    themes = read_themes()
    ids = ["teal", "parchment", "blizzard", "contrast", "night", "graphite"]
    assert [t.id for t in themes] == ids
    assert themes[0].id == REFERENCE
    tokens = set(themes[0].colors)
    assert {"bg", "panel", "text", "accent", "gold", "good", "bad", "muted"} <= tokens
    # round 4 (ADR 0038): the services, the types, depth and the title bar's words
    assert {"svcVendor", "svcHostile", "typeNpc", "typeHere", "void", "card"} <= tokens
    assert {"cardEdge", "inset", "headerText"} <= tokens
    # L5 (plan-second-wave S9): Chat's emote lines, light on the game's dark chat ground
    assert "chatEmote" in tokens
    for t in themes:
        assert set(t.colors) == tokens and set(t.shape) == {"radius", "radiusSmall"}
        assert all(len(c) == 4 and all(0 <= v <= 1 for v in c) for c in t.colors.values())


def test_the_reference_keeps_todays_look():
    teal = read_themes()[0]
    assert teal.colors["accent"] == [0.047, 0.824, 0.616, 1.0]  # 12, 210, 157
    assert teal.colors["gold"] == [1.0, 0.82, 0.0, 1.0]


def test_colours_parse_and_refuse():
    assert parse_color("#ff8000", "x") == [1.0, 0.502, 0.0, 1.0]
    assert parse_color("#ffffff1a", "x")[3] == 0.102
    with pytest.raises(ThemeError, match="no colour"):
        parse_color("red", "teal colors.bad")


def test_a_theme_with_a_missing_token_is_refused(tmp_path):
    for f in THEMES_DIR.glob("*.toml"):
        shutil.copy(f, tmp_path / f.name)
    path = tmp_path / "contrast.toml"
    path.write_text(
        path.read_text(encoding="utf-8").replace('gold = "#ffe600"\n', ""), encoding="utf-8"
    )
    with pytest.raises(ThemeError, match=r"contrast: colours missing \['gold'\]"):
        read_themes(tmp_path)


def test_output_is_deterministic_and_written_atomically(tmp_path):
    out = tmp_path / "Themes.lua"
    assert build_themes(out=out) is True
    first = out.read_bytes()
    build_themes(out=out)
    assert out.read_bytes() == first == emit_themes(read_themes()).encode("utf-8")
    assert first.startswith(b"-- GENERATED by bastians_build") and OUT.name == "Themes.lua"


