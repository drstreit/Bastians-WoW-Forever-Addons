"""The mapart command (B8.4): clientdump tile lists -> Bastians_Map/Generated/MinimapTiles.lua."""

from pathlib import Path

import pytest

from bastians_build.__main__ import main
from bastians_build.mapart import (
    MapArtError,
    build_tiles,
    emit_tiles,
    find_tile_lists,
    read_tile_list,
    tile_key,
    tile_tables,
)

ROOT = Path(__file__).resolve().parents[2]
FIXTURE = ROOT / "tests" / "fixtures" / "mapart"
GOLDEN = FIXTURE / "MinimapTiles.lua"
HINT = (
    "regenerate with: python -m bastians_build mapart --client forever "
    "--tiles tests/fixtures/mapart --out <tmp> and copy Bastians_Map/Generated/MinimapTiles.lua "
    "to tests/fixtures/mapart/"
)


def test_tile_list_is_parsed_and_keyed_by_column_and_row():
    tiles = read_tile_list(FIXTURE / "Azeroth_tiles.txt")
    assert tiles[(31, 48)] == 204453  # Stormwind's tile (client-extraction.md)
    assert len(tiles) == 6
    assert tile_key(31, 48) == 31 * 64 + 48


@pytest.mark.parametrize(
    ("text", "message"),
    [
        ("1\t2\n", "expected"),
        ("a\t2\t3\n", "not integers"),
        ("64\t2\t3\n", "outside"),
        ("1\t2\t0\n", "positive"),
        ("1\t2\t3\n1\t2\t4\n", "twice"),
        ("# only a comment\n", "no tiles"),
    ],
)
def test_bad_tile_lists_are_rejected(tmp_path, text, message):
    path = tmp_path / "Azeroth_tiles.txt"
    path.write_text(text, encoding="utf-8")
    with pytest.raises(MapArtError, match=message):
        read_tile_list(path)


def test_tables_map_directories_to_continents_and_reject_unknown_maps(tmp_path):
    lists = find_tile_lists(FIXTURE)
    assert sorted(lists) == ["Azeroth", "Kalimdor"]
    tables = tile_tables(lists)
    assert tables[0]["directory"] == "Azeroth" and tables[0]["tiles"][tile_key(31, 48)] == 204453
    assert tables[1] == {"directory": "Kalimdor", "tiles": {tile_key(30, 30): 600001}}
    (tmp_path / "Expansion01_tiles.txt").write_text("1\t1\t5\n", encoding="utf-8")
    with pytest.raises(MapArtError, match="no continent"):
        tile_tables(find_tile_lists(tmp_path))
    # with the Map dump every map directory finds its continent id (Outland is Map 530)
    from bastians_build.mapart import directories_from_maps

    maps_json = ROOT / "tests" / "fixtures" / "sources" / "clientdump" / "Map.json"
    directories = directories_from_maps(maps_json)
    assert directories["Expansion01"] == 530 and directories["Azeroth"] == 0
    assert tile_tables(find_tile_lists(tmp_path), directories) == {
        530: {"directory": "Expansion01", "tiles": {tile_key(1, 1): 5}}
    }
    assert build_tiles("retail", tmp_path, tmp_path / "out", maps_json=maps_json)[2] == {530: 1}
    (tmp_path / "empty").mkdir()
    with pytest.raises(MapArtError, match=r"no \*_tiles.txt"):
        find_tile_lists(tmp_path / "empty")
    with pytest.raises(MapArtError, match="not a folder"):
        find_tile_lists(tmp_path / "missing")


def test_committed_golden_table_matches_a_fresh_emit():
    """The Lua tests register exactly what the generator produces (map.md acceptance 2)."""
    text = emit_tiles("forever", tile_tables(find_tile_lists(FIXTURE)))
    assert GOLDEN.is_file(), f"{GOLDEN} missing; {HINT}"
    assert text == GOLDEN.read_text(encoding="utf-8"), HINT
    assert text.startswith("-- GENERATED by bastians_build")
    assert '"Map.RegisterTiles",' in text
    assert 'directory = "Azeroth",' in text and 'directory = "Kalimdor",' in text


def test_a_fixture_is_never_written_into_the_repo_addons_folder(tmp_path, capsys):
    """The dev install links addons/: the golden fixture written there with the default --out
    left the game with one native tile for an evening (21.10.2026)."""
    with pytest.raises(MapArtError, match="refusing"):
        build_tiles("forever", FIXTURE, ROOT / "addons")
    assert not (ROOT / "addons" / "Bastians_Map" / "Generated" / "MinimapTiles.lua.tmp").exists()
    assert main(["mapart", "--client", "forever", "--tiles", str(FIXTURE)]) == 2
    assert "refusing" in capsys.readouterr().err
    # a dry run and any other output folder are fine
    assert build_tiles("forever", FIXTURE, ROOT / "addons", write=False)[1] is False
    assert build_tiles("forever", FIXTURE, tmp_path)[1] is True
    # the data command refuses the fixture world the same way
    argv = ["data", "--client", "forever", "--fixture", "tests/fixtures/world-mini"]
    assert main([*argv, "--out", "addons"]) == 2
    assert "refusing" in capsys.readouterr().err


def test_build_is_idempotent_and_the_cli_reports(tmp_path, capsys):
    path, changed, counts = build_tiles("forever", FIXTURE, tmp_path)
    assert changed and counts == {0: 6, 1: 1}
    assert path == tmp_path / "Bastians_Map" / "Generated" / "MinimapTiles.lua"
    assert not build_tiles("forever", FIXTURE, tmp_path)[1]
    assert not list(path.parent.glob("*.tmp"))
    argv = ["mapart", "--client", "retail", "--tiles", str(FIXTURE), "--out", str(tmp_path)]
    assert main(argv) == 0
    out = capsys.readouterr().out
    assert "continent 0: 6 tiles" in out and "written:" in out
    assert 'client = "retail"' in path.read_text(encoding="utf-8")
    assert main(["mapart", "--client", "forever", "--tiles", str(tmp_path / "nope")]) == 2
    assert "error:" in capsys.readouterr().err


def test_all_sea_tiles_leave_the_table_when_the_overview_index_marks_them(tmp_path):
    """at close zoom Blizzard's black water covered the parchment cells. The
    stitcher records each tile's sea share; tiles at or above `skip_sea` stay out of the table."""
    import json

    from bastians_build.mapart import sea_tiles

    assert sea_tiles(None, 0.98) == {} and sea_tiles(tmp_path / "nope", 0.98) == {}
    index = {
        "map": "Azeroth",
        "mapId": 0,
        "span": 8,
        "pixels": 4,
        "format": "blp",
        "mips": True,
        "sourceTiles": 6,
        "cells": [{"x": 3, "y": 5, "file": "Azeroth_3_5.blp", "adts": 1, "bytes": 1}],
        "tiles": [[31, 31, 0.0], [32, 31, 0.985], [31, 48, 1.0], [33, 32, 0.5]],
    }
    import shutil

    shutil.copy(FIXTURE / "overview" / "Azeroth_3_5.blp", tmp_path / "Azeroth_3_5.blp")
    (tmp_path / "Azeroth_overview.json").write_text(json.dumps(index), encoding="utf-8")
    assert sea_tiles(tmp_path, 0.98) == {"Azeroth": {(32, 31), (31, 48)}}
    assert sea_tiles(tmp_path, 1.0) == {"Azeroth": {(31, 48)}}
    tables = tile_tables(find_tile_lists(FIXTURE), skip=sea_tiles(tmp_path, 0.98))
    assert sorted(tables[0]["tiles"]) == [
        tile_key(31, 31),
        tile_key(31, 32),
        tile_key(32, 32),
        tile_key(33, 32),
    ]
    assert tables[1]["tiles"] == {tile_key(30, 30): 600001}  # untouched
    path, _, counts = build_tiles(
        "forever", FIXTURE, tmp_path / "out", skip=sea_tiles(tmp_path, 0.98)
    )
    assert counts == {0: 4, 1: 1} and "[2032]" not in path.read_text(encoding="utf-8")
