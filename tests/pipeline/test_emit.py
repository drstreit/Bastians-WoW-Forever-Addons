"""The Lua emitter: deterministic, Lua 5.1 safe, format B friendly."""

import pytest

from bastians_build.emit import EmitError, emit_pack, lua_key, lua_number, lua_string, lua_value


def test_strings_are_escaped_for_lua():
    assert lua_string('Wanted: "Hogger"') == '"Wanted: \\"Hogger\\""'
    assert lua_string("Interface\\Icons\\X") == '"Interface\\\\Icons\\\\X"'
    assert lua_string("a\nb\tc") == '"a\\nb\\tc"'
    assert lua_string("bell\x07") == '"bell\\007"'
    assert lua_string("Ümlaut") == '"Ümlaut"'


def test_numbers_are_short_and_stable():
    assert lua_number(448) == "448"
    assert lua_number(0.27) == "0.27"
    assert lua_number(0.1 + 0.2) == "0.3"
    assert lua_number(2.0) == "2"
    assert lua_number(-0.0) == "0"
    assert lua_number(1 / 3) == "0.333333"
    with pytest.raises(EmitError):
        lua_number(float("nan"))
    with pytest.raises(EmitError):
        lua_number(float("inf"))


def test_keys_are_bare_identifiers_or_bracketed():
    assert lua_key("name") == "name"
    assert lua_key("npc.byZone") == '["npc.byZone"]'
    assert lua_key("end") == '["end"]'
    assert lua_key(448) == "[448]"
    with pytest.raises(EmitError):
        lua_key(True)


def test_tables_sort_keys_numbers_first_and_skip_nil_fields():
    text = lua_value({"b": 1, "a": 2, 10: "x", 2: "y", "gone": None})
    assert text == '{\n  [2] = "y",\n  [10] = "x",\n  a = 2,\n  b = 1,\n}'
    assert lua_value({}) == "{}" and lua_value([]) == "{}"


def test_lists_keep_order_and_nil_slots():
    assert lua_value(["Hogger", None, 11]) == '{ "Hogger", nil, 11 }'
    nested = lua_value([[1429, 0.27, 0.86, "eq"], [1429, 0.3, 0.8, "questie"]])
    assert nested == '{ { 1429, 0.27, 0.86, "eq" }, { 1429, 0.3, 0.8, "questie" } }'
    wide = lua_value([[i * 100000 for i in range(20)], [1]])
    # too wide for one line: elements packed into lines up to the width, the short list inline
    assert wide.startswith("{\n  {\n    0, 100000, 200000,")
    assert wide.endswith("\n  },\n  { 1 },\n}")
    assert all(len(line) <= 110 for line in wide.splitlines())
    assert lua_value({3, 1, 2}) == "{ 1, 2, 3 }"  # sets are sorted
    long = lua_value(list(range(60)))
    assert long.startswith("{\n  0, 1, 2,") and long.endswith(", 58, 59,\n}")
    record = lua_value([None, None, 5, {"items": [[1, None]], "src": "att"}, "x"])
    assert record == '{ nil, nil, 5, { items = { { 1, nil } }, src = "att" }, "x" }'


def test_emit_pack_has_header_and_register_call():
    text = emit_pack(
        "world", {"schema": {"npc": ["name"]}, "npc": {448: ["Hogger"]}}, comment="test"
    )
    assert text.startswith("-- GENERATED by bastians_build 0.1.0, do not edit\n-- test\n")
    assert 'B.deferred[#B.deferred + 1] = {\n  "Data.RegisterPack",\n  "world",\n' in text
    assert text.count("Bastians = B") == 1
    assert text == emit_pack(
        "world", {"npc": {448: ["Hogger"]}, "schema": {"npc": ["name"]}}, comment="test"
    )
    assert text.endswith("}\n")
    with pytest.raises(EmitError):
        lua_value(object())
