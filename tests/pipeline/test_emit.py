"""The Lua emitter: deterministic, Lua 5.1 safe, format B friendly."""

import pytest

from bastians_build.emit import EmitError, emit_pack, lua_key, lua_number, lua_string, lua_value


def test_strings_are_escaped_for_lua():
    assert lua_string('Wanted: "Hogger"') == '"Wanted: \\"Hogger\\""'
    assert lua_string("Interface\\Icons\\X") == '"Interface\\\\Icons\\\\X"'
    assert lua_string("a\nb\tc") == '"a\\nb\\tc"'
    assert lua_string("bell\x07") == '"bell\\007"'
    assert lua_string("Ümlaut") == '"Ümlaut"'


def test_numbers_are_short_and_stable():
    assert lua_number(448) == "448"
    assert lua_number(0.27) == "0.27"
    assert lua_number(0.1 + 0.2) == "0.3"
    assert lua_number(2.0) == "2"
    assert lua_number(-0.0) == "0"
    assert lua_number(1 / 3) == "0.333333"
    with pytest.raises(EmitError):
        lua_number(float("nan"))
    with pytest.raises(EmitError):
        lua_number(float("inf"))


def test_keys_are_bare_identifiers_or_bracketed():
    assert lua_key("name") == "name"
    assert lua_key("npc.byZone") == '["npc.byZone"]'
    assert lua_key("end") == '["end"]'
    assert lua_key(448) == "[448]"
    with pytest.raises(EmitError):
        lua_key(True)


def test_tables_sort_keys_numbers_first_and_skip_nil_fields():
    text = lua_value({"b": 1, "a": 2, 10: "x", 2: "y", "gone": None})
    assert text == '{\n  [2] = "y",\n  [10] = "x",\n  a = 2,\n  b = 1,\n}'
    assert lua_value({}) == "{}" and lua_value([]) == "{}"


def test_lists_keep_order_and_nil_slots():
    assert lua_value(["Hogger", None, 11]) == '{ "Hogger", nil, 11 }'
    nested = lua_value([[1429, 0.27, 0.86, "eq"], [1429, 0.3, 0.8, "questie"]])
    assert nested == '{ { 1429, 0.27, 0.86, "eq" }, { 1429, 0.3, 0.8, "questie" } }'
    wide = lua_value([[i * 100000 for i in range(20)], [1]])
    # too wide for one line: elements packed into lines up to the width, the short list inline
    assert wide.startswith("{\n  {\n    0, 100000, 200000,")
    assert wide.endswith("\n  },\n  { 1 },\n}")
    assert all(len(line) <= 110 for line in wide.splitlines())
    assert lua_value({3, 1, 2}) == "{ 1, 2, 3 }"  # sets are sorted
    long = lua_value(list(range(60)))
    assert long.startswith("{\n  0, 1, 2,") and long.endswith(", 58, 59,\n}")
    record = lua_value([None, None, 5, {"items": [[1, None]], "src": "att"}, "x"])
    assert record == '{ nil, nil, 5, { items = { { 1, nil } }, src = "att" }, "x" }'


def test_emit_pack_has_header_and_register_call():
    text = emit_pack(
        "world", {"schema": {"npc": ["name"]}, "npc": {448: ["Hogger"]}}, comment="test"
    )
    assert text.startswith("-- GENERATED by bastians_build 0.1.0, do not edit\n-- test\n")
    assert 'B.deferred[#B.deferred + 1] = {\n  "Data.RegisterPack",\n  "world",\n' in text
    assert text.count("Bastians = B") == 1
    assert text == emit_pack(
        "world", {"npc": {448: ["Hogger"]}, "schema": {"npc": ["name"]}}, comment="test"
    )
    assert text.endswith("}\n")
    with pytest.raises(EmitError):
        lua_value(object())


def compiled(text: str):
    """The pack a generated file registers, as real Lua 5.1 builds it (lupa)."""
    from lupa import lua51

    lua = lua51.LuaRuntime(unpack_returned_tuples=True)
    lua.globals().SRC = text
    lua.execute(
        """
        local f, err = loadstring(SRC, "@Pack.lua")
        ERR = err
        if f then
          Bastians = nil
          f()
          CALL = Bastians.deferred[1]
        end
        """
    )
    return lua, lua.globals().ERR


def test_a_pack_heavier_than_one_lua_function_holds_is_written_in_parts():
    """Lua 5.1 holds 262,143 constants in a function and a generated file is one chunk: the
    Market pack passed that on 17.11.2026 ("constant table overflow", the pack did not load).
    A table that heavy is written in parts, each a function of its own; the loader sees the same
    table, and a lighter pack's text does not change."""
    rows = {i: {"name": f"Item {i}", "price": i * 3} for i in range(1, 150_001)}
    realms = {f"realm-{r}": {i: [i, i + 1] for i in range(1, 30_001)} for r in range(8)}
    pack = {"build": "x", "schema": {"item": ["name", "price"]}, "item": rows, "realm": realms}
    text = emit_pack("market", pack)
    lua, err = compiled(text)
    assert err is None, err
    assert lua.eval("CALL[1]") == "Data.RegisterPack" and lua.eval("CALL[2]") == "market"
    lua.execute(
        """
        local pack = CALL[3]
        N = 0
        for _ in pairs(pack.item) do N = N + 1 end
        FIRST, LAST = pack.item[1], pack.item[150000]
        REALMS, DEEP = 0, 0
        for _, realm in pairs(pack.realm) do
          REALMS = REALMS + 1
          for _ in pairs(realm) do DEEP = DEEP + 1 end
        end
        PAIR = pack.realm["realm-7"][30000]
        """
    )
    assert lua.eval("N") == 150_000
    # a record stays its literal, compiled on demand
    assert lua.eval("FIRST") == '{ name = "Item 1", price = 3 }'
    assert lua.eval("LAST") == '{ name = "Item 150000", price = 450000 }'
    assert lua.eval("REALMS") == 8 and lua.eval("DEEP") == 240_000  # many middling tables too
    assert list(lua.eval("PAIR").values()) == [30000, 30001]
    assert emit_pack("market", pack) == text  # deterministic
    # without the parts the same pack does not compile: the test holds the cause, not a guess
    import bastians_build.emit as emit

    limit, emit.CONSTANTS_MAX = emit.CONSTANTS_MAX, 10**9
    try:
        _, err = compiled(emit_pack("market", pack))
    finally:
        emit.CONSTANTS_MAX = limit
    assert "constant table overflow" in str(err)
    # a light pack is written as before, byte for byte
    light = {"build": "x", "schema": {"item": ["name"]}, "item": {1: {"name": "Linen"}}}
    assert "(function()" not in emit_pack("items", light)
