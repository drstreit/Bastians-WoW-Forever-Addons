"""Tests for tools/api_stubs.py on a tiny fixture world. Everything is written to tmp_path."""

from pathlib import Path

import api_stubs
import pytest

FIXTURES = Path(__file__).resolve().parent.parent / "fixtures" / "wow-ui-source"
RC = """std = "lua51"
read_globals = {
  "CreateFrame",
  "UIParent",
}
exclude_files = { "addons/**/Generated/**" }
"""


@pytest.fixture(scope="module")
def parsed():
    return {b: api_stubs.parse_branch(FIXTURES / b) for b in api_stubs.BRANCHES}


@pytest.fixture
def root(tmp_path):
    (tmp_path / ".luacheckrc").write_text(RC, encoding="utf-8", newline="\n")
    return tmp_path


def test_parse_functions_events_enums(parsed):
    forever = parsed["forever"]
    assert sorted(forever["functions"]) == [
        "C_QuestLog.GetInfo",
        "C_QuestLog.GetQuestTagInfo",
        "C_TaxiMap.GetAllTaxiNodes",
        "C_TaxiMap.GetTaxiNodesForMap",
        "C_TaxiMap.ShouldMapShowTaxiNodes",
        "GetServerTime",
    ]
    assert forever["functions"]["C_QuestLog.GetInfo"]["args"] == [
        {"name": "questLogIndex", "type": "number", "nilable": False}
    ]
    assert forever["functions"]["C_QuestLog.GetQuestTagInfo"]["returns"][0] == {
        "name": "tagInfo",
        "type": "table",
        "nilable": True,
        "innerType": "QuestTagInfo",
    }
    assert forever["events"]["QUEST_ACCEPTED"]["payload"][0]["name"] == "questID"
    assert forever["events"]["TAXIMAP_CLOSED"]["payload"] == []
    assert forever["enums"]["FlightPathState"] == {"Current": 0, "Reachable": 1, "Unreachable": 2}
    assert forever["enums"]["QuestTagType"] == {"Tag": 0, "Profession": 1}


def test_constants_referencing_enum_do_not_break_loading(parsed):
    # FlightConstantsDocumentation.lua reads Enum.* and does arithmetic on Constants.*.
    assert "GetServerTime" in parsed["forever"]["functions"]
    assert "GetServerTime" in parsed["live"]["functions"]


def test_render_api_is_deterministic_and_valid_lua(parsed):
    from lupa.lua51 import LuaRuntime

    meta = api_stubs.load_meta(FIXTURES / "forever")
    first = api_stubs.render_api(parsed["forever"], "forever", meta)
    assert first == api_stubs.render_api(parsed["forever"], "forever", meta)
    assert first.startswith(
        "-- GENERATED by tools/api_stubs.py from Gethe/wow-ui-source forever "
        "1111111111111111111111111111111111111111 (1.60.1 (70450)), do not edit\n"
    )
    assert "\r" not in first
    table = LuaRuntime().execute(first)
    assert table["functions"]["C_TaxiMap.GetAllTaxiNodes"]["args"][1]["name"] == "uiMapID"
    assert table["enums"]["FlightPathState"]["Reachable"] == 1
    assert table["events"]["QUEST_ACCEPTED"]["payload"][1]["nilable"] is False


