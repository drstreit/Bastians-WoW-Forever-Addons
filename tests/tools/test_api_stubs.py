def test_generate_writes_files_and_is_idempotent(root):
    assert api_stubs.main(["generate", "--cache", str(FIXTURES), "--root", str(root)]) == 0
    gen = root / "tests" / "lua" / "mock" / "Generated"
    names = sorted(p.name for p in gen.iterdir())
    assert names == [
        "api_forever.lua",
        "api_retail.lua",
        "globals_forever_only.lua",
        "globals_retail_only.lua",
        "globals_shared.lua",
    ]
    snapshot = {p: p.read_bytes() for p in [*gen.iterdir(), root / ".luacheckrc"]}
    assert b"\r" not in b"".join(snapshot.values())
    assert api_stubs.main(["generate", "--cache", str(FIXTURES), "--root", str(root)]) == 0
    assert {p: p.read_bytes() for p in snapshot} == snapshot
    report = (root / "data" / "api" / "diff_forever_vs_retail.md").read_text(encoding="utf-8")
    assert "| Functions | 6 | 5 | 4 | 2 | 1 |" in report
    assert "`C_TaxiMap.ShouldMapShowTaxiNodes`" in report
    assert "`C_QuestLog` | `GetInfo`, `GetQuestTagInfo`" in report


def test_globals_files_are_plain_arrays(root):
    from lupa.lua51 import LuaRuntime

    api_stubs.main(["generate", "--cache", str(FIXTURES), "--root", str(root)])
    shared = root / "tests/lua/mock/Generated/globals_shared.lua"
    text = shared.read_text(encoding="utf-8")
    assert text.startswith("-- GENERATED by tools/api_stubs.py from Gethe/wow-ui-source forever")
    names = list(LuaRuntime().execute(text).values())
