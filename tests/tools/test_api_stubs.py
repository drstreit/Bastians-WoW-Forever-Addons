def test_luacheckrc_keeps_handwritten_content(root):
    api_stubs.main(["generate", "--cache", str(FIXTURES), "--root", str(root)])
    rc = (root / ".luacheckrc").read_text(encoding="utf-8")
    assert 'std = "lua51"' in rc
    assert "exclude_files = " in rc
    assert 'local handwritten_globals = {\n  "CreateFrame",\n  "UIParent",\n}' in rc
    assert rc.count(api_stubs.BEGIN_MARK) == 1
    assert 'files["addons/Bastians_Core/Compat/"]' in rc
    assert 'files["addons/Bastians_Probe/"]' in rc
    assert '"C_QuestLog"' in rc


def test_update_luacheckrc_replaces_only_the_marked_section():
    block1 = f"{api_stubs.BEGIN_MARK}\nold\n{api_stubs.END_MARK}\n"
    text = f"-- top\nlocal handwritten_globals = {{ 'X' }}\n{block1}-- bottom\n"
    new_block = f"{api_stubs.BEGIN_MARK}\nnew\n{api_stubs.END_MARK}\n"
    out = api_stubs.update_luacheckrc(text, new_block)
    assert out == f"-- top\nlocal handwritten_globals = {{ 'X' }}\n{new_block}-- bottom\n"
    assert api_stubs.update_luacheckrc(out, new_block) == out


def test_check_detects_a_change(root, capsys):
    argv = ["--cache", str(FIXTURES), "--root", str(root)]
    assert api_stubs.main(["check", *argv]) == 1  # nothing committed yet
    api_stubs.main(["generate", *argv])
    assert api_stubs.main(["check", *argv]) == 0
    stub = root / "tests/lua/mock/Generated/api_retail.lua"
    stub.write_bytes(stub.read_bytes().replace(b"GetActiveSoulbindID", b"GetSomethingElse"))
    capsys.readouterr()
    assert api_stubs.main(["check", *argv]) == 1
    assert "api_retail.lua" in capsys.readouterr().out


def test_missing_cache_is_a_clean_error(root, tmp_path, capsys):
    code = api_stubs.main(["generate", "--cache", str(tmp_path / "nope"), "--root", str(root)])
    assert code == 2
    assert "fetch" in capsys.readouterr().err
