"""tools/city_sheet.py: the tiles, the padding, the manifest; the output is deterministic."""

import importlib.util
from pathlib import Path

from PIL import Image

TOOL = Path(__file__).resolve().parents[2] / "tools" / "city_sheet.py"
spec = importlib.util.spec_from_file_location("city_sheet", TOOL)
city_sheet = importlib.util.module_from_spec(spec)
spec.loader.exec_module(city_sheet)


def test_a_sheet_takes_whole_tiles():
    assert city_sheet.grid(4008, 2672) == (3, 4)
    assert city_sheet.grid(1024, 1024) == (1, 1)
    assert city_sheet.grid(1025, 1) == (1, 2)


def test_the_padding_repeats_the_edge():
    sheet = Image.new("RGB", (1030, 8), (10, 20, 30))
    sheet.putpixel((1029, 0), (200, 100, 50))
    cut = {(r, c): t for r, c, t in city_sheet.tiles(sheet)}
    assert sorted(cut) == [(0, 0), (0, 1)]
    assert cut[0, 1].size == (1024, 1024)
    assert cut[0, 1].getpixel((5, 0)) == (200, 100, 50)  # the sheet's last pixel
    assert cut[0, 1].getpixel((900, 0)) == (200, 100, 50)  # and the padding beside it
    assert cut[0, 0].getpixel((0, 900)) == (10, 20, 30)  # the bottom edge carries down


def test_the_manifest_names_every_field():
    text = city_sheet.manifest(
        [
            {
                "ui": 1453,
                "name": "Stormwind City",
                "continent": 0,
                "wx": (-9154.17, -7995.83),
                "wy": (-14.584, 1722.92),
                "w": 4008,
                "h": 2672,
                "rows": 3,
                "cols": 4,
            }
        ]
    )
    assert text.startswith("-- GENERATED by tools/city_sheet.py, do not edit\n")
    assert "wx = { -9154.17, -7995.83 }" in text and "wy = { -14.584, 1722.92 }" in text
    assert "rows = 3, cols = 4" in text
    assert (
        'path = "Interface\\\\AddOns\\\\Bastians_Map_Art\\\\Generated\\\\Cities\\\\1453_"' in text
    )


def test_the_same_picture_gives_the_same_bytes(tmp_path):
    picture = tmp_path / "sheet.png"
    Image.effect_noise((1100, 40), 30).convert("RGB").save(picture)
    a = city_sheet.build(1453, picture, tmp_path / "a")
    b = city_sheet.build(1453, picture, tmp_path / "b")
    assert a == b and a["rows"] == 1 and a["cols"] == 2
    first = tmp_path / "a" / "Generated" / "Cities" / "1453_0_1.blp"
    second = tmp_path / "b" / "Generated" / "Cities" / "1453_0_1.blp"
    assert first.read_bytes()[:4] == b"BLP2" and first.read_bytes() == second.read_bytes()
