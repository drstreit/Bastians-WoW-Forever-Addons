"""Deterministic Lua emitter: the same Python value always gives the same bytes (CLAUDE.md §6).

Tables are written with sorted keys (numbers first, then strings), floats with at most six decimals
and no trailing zeros, strings escaped for Lua 5.1. Lists keep their order; ``None`` inside a list
becomes ``nil`` so positional records keep their slots.
"""

from __future__ import annotations

import math
import re
from collections.abc import Mapping, Sequence

from bastians_build import __version__

HEADER = f"-- GENERATED by bastians_build {__version__}, do not edit"
IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
LUA_KEYWORDS = frozenset(
    {
        "and",
        "break",
        "do",
        "else",
        "elseif",
        "end",
        "false",
        "for",
        "function",
        "if",
        "in",
        "local",
        "nil",
        "not",
        "or",
        "repeat",
        "return",
        "then",
        "true",
        "until",
        "while",
    }
)
INLINE_MAX = (
    110  # a list (of scalars and short lists) up to this width stays on one line (StyLua width)
)
_ESCAPES = {"\\": "\\\\", '"': '\\"', "\n": "\\n", "\r": "\\r", "\t": "\\t"}


class EmitError(ValueError):
    """A value that Lua cannot hold (NaN, infinity, an unsupported type)."""


def lua_string(text: str) -> str:
    out = []
    for ch in text:
        if ch in _ESCAPES:
            out.append(_ESCAPES[ch])
        elif ord(ch) < 32 or ord(ch) == 127:
            out.append(f"\\{ord(ch):03d}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def lua_number(value: float) -> str:
    if isinstance(value, bool):
        raise EmitError("bool is not a number")
    if isinstance(value, int):
        return str(value)
    if math.isnan(value) or math.isinf(value):
        raise EmitError(f"cannot emit {value!r}")
    if value == int(value) and abs(value) < 1e15:
        return str(int(value))
    text = f"{value:.6f}".rstrip("0").rstrip(".")
    return text if text not in ("", "-0") else "0"


def lua_key(key: object) -> str:
    if isinstance(key, bool):
        raise EmitError("bool keys are not supported")
    if isinstance(key, int | float):
        return f"[{lua_number(key)}]"
    if isinstance(key, str):
        if IDENTIFIER.match(key) and key not in LUA_KEYWORDS:
            return key
        return f"[{lua_string(key)}]"
    raise EmitError(f"unsupported key {key!r}")


def _sort_key(key: object) -> tuple[int, object]:
    if isinstance(key, int | float) and not isinstance(key, bool):
        return (0, key)
    return (1, str(key))


def _is_scalar(value: object) -> bool:
    return value is None or isinstance(value, str | int | float | bool)


class Literal(str):
    """Lua source kept as text: emitted as a long-bracket string, so the client compiles it only
    when a record is first read (data.md "Pack format", format A since 20.10.2026)."""


def compact(value: object) -> Literal:
    """The one-line Lua form of a value, whatever its width (records inside a pack string)."""
    text = _inline_value(value, limit=False)
    if text is None:
        raise EmitError(f"unsupported value {value!r}")
    return Literal(text)


def long_string(text: str) -> str:
    """``[=[text]=]`` with enough ``=`` that the text cannot close it early."""
    level = 1
    while f"]{'=' * level}]" in text:
        level += 1
    eq = "=" * level
    return f"[{eq}[{text}]{eq}]"


def lua_value(value: object, indent: int = 0) -> str:
    """Render any supported Python value as Lua source."""
    if value is None:
        return "nil"
    if value is True:
        return "true"
    if value is False:
        return "false"
    if isinstance(value, int | float):
        return lua_number(value)
    if isinstance(value, Literal):
        return long_string(value)
    if isinstance(value, str):
        return lua_string(value)
    if isinstance(value, Mapping):
        return _lua_table(value, indent)
    if isinstance(value, Sequence | set | frozenset):
        items = sorted(value, key=_sort_key) if isinstance(value, set | frozenset) else list(value)
        return _lua_list(items, indent)
    raise EmitError(f"unsupported value {value!r}")


def _inline_value(value: object, limit: bool = True) -> str | None:
    """One-line form of a scalar, list or table whose parts all fit; None otherwise.
    With ``limit`` off the width does not matter (record literals inside pack strings)."""
    if _is_scalar(value):
        return lua_value(value)
    if isinstance(value, Mapping):
        return _inline_table(value, limit)
    if isinstance(value, Sequence | set | frozenset):
        items = sorted(value, key=_sort_key) if isinstance(value, set | frozenset) else list(value)
        return _inline_list(items, limit)
    return None


def _fits(text: str, limit: bool) -> str | None:
    return text if not limit or len(text) <= INLINE_MAX else None


def _inline_list(items: list, limit: bool = True) -> str | None:
    """One-line form of a list of scalars, short lists and short tables; None if it does not fit."""
    parts = []
    for x in items:
        part = _inline_value(x, limit)
        if part is None:
            return None
        parts.append(part)
    return _fits("{ " + ", ".join(parts) + " }" if parts else "{}", limit)


def _inline_table(table: Mapping, limit: bool = True) -> str | None:
    parts = []
    for key in sorted(table, key=_sort_key):
        value = table[key]
        if value is None:
            continue
        part = _inline_value(value, limit)
        if part is None:
            return None
        parts.append(f"{lua_key(key)} = {part}")
    return _fits("{ " + ", ".join(parts) + " }" if parts else "{}", limit)


def _lua_list(items: list, indent: int) -> str:
    """A list that does not fit one line: elements packed into lines up to INLINE_MAX wide, an
    element that spans lines on lines of its own. Positional records (data.md format B) are mostly
    nils and short lists, so one line per element would be whitespace (the first retail quest pack
    was 17 MB that way, 20.10.2026)."""
    if not items:
        return "{}"
    inline = _inline_list(items)
    if inline is not None:
        return inline
    pad = "  " * (indent + 1)
    lines: list[str] = []
    current = ""
    for x in items:
        text = lua_value(x, indent + 1) + ","
        if "\n" in text:
            if current:
                lines.append(pad + current)
                current = ""
            lines.append(pad + text)
        elif current and len(pad) + len(current) + 1 + len(text) > INLINE_MAX:
            lines.append(pad + current)
            current = text
        else:
            current = (current + " " + text) if current else text
    if current:
        lines.append(pad + current)
    return "{\n" + "\n".join(lines) + "\n" + "  " * indent + "}"


def _lua_table(table: Mapping, indent: int) -> str:
    if not table:
        return "{}"
    pad = "  " * (indent + 1)
    lines = []
    for key in sorted(table, key=_sort_key):
        value = table[key]
        if value is None:
            continue  # a nil field is the same as an absent one in a table
        lines.append(f"{pad}{lua_key(key)} = {lua_value(value, indent + 1)},")
    if not lines:
        return "{}"
    return "{\n" + "\n".join(lines) + "\n" + "  " * indent + "}"


def emit_call(function: str, args: Sequence, comment: str | None = None) -> str:
    """A generated file that is one deferred call: header, optional comment, then the call queued
    as `{ "Data.RegisterPack", arg, ... }` on `Bastians.deferred` (core-contracts "Generated
    files"). The client may run the file before Core or its consumer exists (seen on the Forever
    beta, 20.10.2026), so the file creates the one global if needed and never calls into a module;
    Core's `Bastians.Deliver()` makes the call once the target function is there."""
    if not function.startswith("Bastians."):
        raise ValueError(f"emit_call: {function!r} is not a Bastians.* function")
    lines = [HEADER]
    if comment:
        lines.append(f"-- {comment}")
    lines += [
        "local B = Bastians or {}",
        "Bastians = B",
        "B.deferred = B.deferred or {}",
        "B.deferred[#B.deferred + 1] = {",
        f"  {lua_string(function[len('Bastians.') :])},",
    ]
    for a in args:
        lines.append(f"  {lua_value(a, 1)},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def emit_pack(name: str, pack: Mapping, comment: str | None = None) -> str:
    """The text of a pack file: header, optional comment line, RegisterPack call (data.md).

    Every record row of a schema type goes out as one long-bracket string holding its Lua literal
    (format A): the loader compiles a record on first access, so a loaded pack costs about its file
    size in memory instead of five times that (measured 20.10.2026, data.md "Pack format")."""
    packed = dict(pack)
    for record_type in pack.get("schema") or {}:
        rows = pack.get(record_type)
        if isinstance(rows, Mapping):
            packed[record_type] = {rid: compact(row) for rid, row in rows.items()}
    return emit_call("Bastians.Data.RegisterPack", [name, packed], comment)


def emit_transforms(
    table: Mapping[int, Sequence],
    comment: str | None = None,
    continents: Mapping[int, str] | None = None,
) -> str:
    """MapTransforms.lua: `[uiMapID] = { continent, wx0, wxDx, wxDy, wy0, wyDx, wyDy }`, plus the
    continent names `{ [Map.db2 id] = name }` when the build knew them (Map and Route list them)."""
    args: list = [table]
    if continents:
        args.append(dict(sorted(continents.items())))
    return emit_call("Bastians.Data.RegisterTransforms", args, comment)
