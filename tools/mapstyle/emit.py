"""The Bastian map's style addons (ADR 0027): from the encoded cells of a build, each style addon's
Generated folder: Style.lua (the cell table the Map registers through Bastians.deferred) and the
textures in Near/ and Far/. Deterministic: the same cells give the same files."""

from __future__ import annotations

import json
import shutil
from pathlib import Path

from .cells import FAR_SPAN, NEAR_SPAN

ADDONS = {
    "blizzard": ("Bastians_Map_Blizzard", "Blizzard", 5),  # ADR 0036
    "modern": ("Bastians_Map_Modern", "Modern", 10),
    "pencil": ("Bastians_Map_Pencil", "Pencil", 20),
    "parchment": ("Bastians_Map_Parchment", "Parchment", 30),
}
GRID = 64


def _cells(folder: Path) -> dict[int, list[tuple[int, int]]]:
    out: dict[int, list[tuple[int, int]]] = {}
    for path in sorted(folder.glob("*.blp")):
        continent, cx, cy = (int(v) for v in path.stem.split("_"))
        out.setdefault(continent, []).append((cx, cy))
    return out


def _table(cells: dict[int, list[tuple[int, int]]], span: int, indent: str) -> str:
    grid = GRID // span
    lines = []
    for continent in sorted(cells):
        keys = sorted(cx * grid + cy for cx, cy in cells[continent])
        lines.append(f"{indent}[{continent}] = {{ {', '.join(str(k) for k in keys)} }},")
    return "\n".join(lines)


def _lua_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def labels_lua(labels: dict[int, list[dict]], indent: str) -> str:
    """The style's own place names (ADR 0036): { text, wx, wy, height in yards, kind, area id or
    false, level } per continent."""
    lines = []
    for continent in sorted(labels):
        lines.append(f"{indent}[{continent}] = {{")
        for e in labels[continent]:
            area = e["area"] if e.get("area") else "false"
            lines.append(
                f"{indent}  {{ {_lua_string(e['text'])}, {e['wx']}, {e['wy']}, {e['height']}, "
                f'"{e["kind"]}", {area}, {e["level"]} }},'
            )
        lines.append(f"{indent}}},")
    return "\n".join(lines)


def style_lua(
    style: str, client: str, build: str, near: dict, far: dict, labels: dict | None = None
) -> str:
    addon, title, order = ADDONS[style]
    base = f"Interface\\\\AddOns\\\\{addon}\\\\Generated\\\\"
    counts = ", ".join(
        f"continent {c}: {len(near.get(c, []))} near, {len(far.get(c, []))} far cells"
        for c in sorted(set(near) | set(far))
    )
    labels_block = ""
    if labels:
        labels_block = "\n    labels = {\n" + labels_lua(labels, "      ") + "\n    },"
    return f"""-- GENERATED by tools/mapstyle, do not edit
-- Bastian's map style "{style}" for {client} ({counts})
local B = Bastians or {{}}
Bastians = B
B.deferred = B.deferred or {{}}
B.deferred[#B.deferred + 1] = {{
  "Map.RegisterStyle",
  {{
    key = "{style}",
    title = "{title}",
    order = {order},
    client = "{client}",
    build = "{build}",
    near = {{
      path = "{base}Near\\\\",
      span = {NEAR_SPAN},
      continents = {{
{_table(near, NEAR_SPAN, "        ")}
      }},
    }},
    far = {{
      path = "{base}Far\\\\",
      span = {FAR_SPAN},
      continents = {{
{_table(far, FAR_SPAN, "        ")}
      }},
    }},{labels_block}
  }},
}}
"""


def emit(cells: Path, out: Path, client: str, build: str, styles: list[str]) -> list[Path]:
    """Writes <out>/<addon>/Generated/ for each style; stale textures there are removed."""
    written = []
    for style in styles:
        addon = ADDONS[style][0]
        gen = out / addon / "Generated"
        near, far = _cells(cells / style / "near"), _cells(cells / style / "far")
        for part, src in (("Near", cells / style / "near"), ("Far", cells / style / "far")):
            dst = gen / part
            dst.mkdir(parents=True, exist_ok=True)
            wanted = {p.name for p in src.glob("*.blp")}
            for old in dst.glob("*.blp"):
                if old.name not in wanted:
                    old.unlink()
            for name in sorted(wanted):
                target = dst / name
                data = (src / name).read_bytes()
                if not target.is_file() or target.read_bytes() != data:
                    shutil.copyfile(src / name, target)
        lua = gen / "Style.lua"
        labels = None
        names = cells / style / "labels.json"
        if names.is_file():  # the Blizzard style's names (tools/map_blizzard.py labels)
            labels = {int(k): v for k, v in json.loads(names.read_text(encoding="utf-8")).items()}
        text = style_lua(style, client, build, near, far, labels)
        tmp = lua.with_suffix(".tmp")
        tmp.write_text(text, encoding="utf-8", newline="\n")
        tmp.replace(lua)
        written.append(gen)
    return written
